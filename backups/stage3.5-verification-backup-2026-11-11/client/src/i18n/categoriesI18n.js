const normalizeMap = (map) => {
  const index = new Map();
  if (!map) return index;
  for (const [k, v] of Object.entries(map)) {
    index.set(k.trim().toLowerCase(), v);
  }
  return index;
};

const CATEGORY_INDEX = {
  hi: normalizeMap(CATEGORY_TRANSLATIONS.hi),
  mr: normalizeMap(CATEGORY_TRANSLATIONS.mr),
};

const SUBCATEGORY_INDEX = {
  hi: normalizeMap(SUBCATEGORY_TRANSLATIONS.hi),
  mr: normalizeMap(SUBCATEGORY_TRANSLATIONS.mr),
};

export function translateCategoryName(name, lang) {
  if (!name || typeof name !== 'string') return name || '';
  if (!lang || lang === 'en') return name;
  const key = name.trim().toLowerCase();
  return (
    CATEGORY_INDEX[lang]?.get(key) ||
    SUBCATEGORY_INDEX[lang]?.get(key) ||
    name
  );
}

export function translateSubcategoryName(name, lang) {
  if (!name || typeof name !== 'string') return name || '';
  if (!lang || lang === 'en') return name;
  const key = name.trim().toLowerCase();
  return (
    SUBCATEGORY_INDEX[lang]?.get(key) ||
    CATEGORY_INDEX[lang]?.get(key) ||
    name
  );
}
